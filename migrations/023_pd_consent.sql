-- 023: фиксация согласия на обработку персональных данных.
--
-- Зачем колонки, а не «галочка стоит — значит согласен»: по ст. 9 152-ФЗ
-- доказывать наличие согласия обязан оператор. Если предъявить нечего,
-- согласие считается неполученным, и сам факт галочки на форме ничего не
-- доказывает — форму можно поменять задним числом. Поэтому пишем момент и
-- редакцию документа, действовавшую в тот момент: текст согласия со временем
-- меняется, и «согласился с v1» и «согласился с v2» — разные события.
--
-- NULL у существующих аккаунтов — честное «согласие в таком виде не собиралось».
-- Не заполняем задним числом: это была бы подделка доказательства.

alter table users add column if not exists pd_consent_at      timestamptz;
alter table users add column if not exists pd_consent_version text;

comment on column users.pd_consent_at is
  'Момент, когда пользователь дал согласие на обработку ПДн (ст. 9 152-ФЗ). NULL — согласие в явном виде не собиралось.';
comment on column users.pd_consent_version is
  'Редакция текста согласия (страница /consent), действовавшая в момент его дачи.';
